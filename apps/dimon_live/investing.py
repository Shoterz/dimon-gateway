def portfolio(connection: sqlite3.Connection, user_id: str, now: datetime) -> dict:
    holdings = []
    for row in connection.execute(
        "SELECT * FROM holdings WHERE user_id = ? AND quantity_e4 > 0 ORDER BY symbol", (user_id,)
    ).fetchall():
        snap = market.snapshot(row["symbol"], now)
        value = round(row["quantity_e4"] * snap["price_minor"] / UNIT)
        holdings.append({
            "symbol": row["symbol"], "name": snap["name"], "kind": snap["kind"], "risk_level": snap["risk_level"],
            "quantity_e4": row["quantity_e4"], "quantity": units(row["quantity_e4"]),
            "price_minor": snap["price_minor"], "change_1d_pct": snap["change_1d_pct"],
            "value_minor": value, "cost_minor": row["cost_minor"], "gain_minor": value - row["cost_minor"],
            "gain_pct": round((value - row["cost_minor"]) / row["cost_minor"] * 100, 2) if row["cost_minor"] else 0.0,
        })
    total = sum(h["value_minor"] for h in holdings)
    cost = sum(h["cost_minor"] for h in holdings)
    for holding in holdings:
        holding["weight_pct"] = round(holding["value_minor"] / total * 100, 1) if total else 0.0
    plans = [
        {"plan_id": p["plan_id"], "name": p["name"], "monthly_minor": p["monthly_minor"],
         "allocations": json.loads(p["allocations_json"]), "next_run_at": p["next_run_at"], "status": p["status"]}
        for p in connection.execute(
            "SELECT * FROM investment_plans WHERE user_id = ? AND status = 'ACTIVE' ORDER BY created_at", (user_id,)
        ).fetchall()
    ]
    trades = [
        {**dict(t), "name": market.BY_SYMBOL[t["symbol"]].name, "quantity": units(t["quantity_e4"])}
        for t in connection.execute(
            "SELECT * FROM trades WHERE user_id = ? ORDER BY executed_at DESC, rowid DESC LIMIT 10", (user_id,)
        ).fetchall()
    ]
    savings = connection.execute("SELECT balance_minor FROM accounts WHERE account_id = ?", (SOURCE_ACCOUNT_ID,)).fetchone()
    return {
        "profile": profile(connection, user_id),
        "holdings": holdings,
        "total_value_minor": total,
        "total_cost_minor": cost,
        "total_gain_minor": total - cost,
        "cash_minor": savings["balance_minor"] if savings else 0,
        "plans": plans,
        "recent_trades": trades,
        "market": [market.snapshot(i.symbol, now) for i in market.CATALOG],
        "questions": list(QUESTIONS),
        "disclaimer": market.DISCLAIMER,
    }
