"""Investing: orders, holdings, monthly plans, suggestions and projections.

The same rule as payments applies: nothing is bought or sold until the
account holder confirms the exact order with their face and device. Orders
are built by deterministic rules from the user's own words (the instrument,
buy or sell, and the quantity or amount); the language model is not involved.

Suggestions ("what's trending", long-term plans) are computed from the
simulated market data and the user's risk profile, never generated by the
model, and each one lists its risks next to its strengths.
"""

