def future_value(monthly_minor: int, years: int, annual_rate: float) -> int:
    months = years * 12
    if annual_rate == 0:
        return monthly_minor * months
    r = annual_rate / 12
    return round(monthly_minor * ((1 + r) ** months - 1) / r * (1 + r))


def plan_suggestions(risk_score: int | None, horizon_years: int | None, monthly_minor: int | None = None,
                     years: int | None = None) -> dict:
    monthly = monthly_minor or 30_000
    horizon = years or horizon_years or 10
    fitting = [t for t in PLAN_TEMPLATES if risk_score is None or t.risk_level <= risk_score]
    best = fitting[-1] if fitting else PLAN_TEMPLATES[0]
    if horizon <= 3:
        best = PLAN_TEMPLATES[0]      # short horizons: keep it safe whatever the profile
    plans = []
    for template in PLAN_TEMPLATES:
        low, mid, high = (future_value(monthly, horizon, rate) for rate in template.returns)
        plans.append({
            "key": template.key,
            "name": template.name,
            "risk_level": template.risk_level,
            "idea": template.idea,
            "allocations": [
                {"symbol": symbol, "name": market.BY_SYMBOL[symbol].name, "percent": pct}
                for symbol, pct in template.allocations
            ],
            "assumed_returns_pct": [round(rate * 100, 1) for rate in template.returns],
            "monthly_minor": monthly,
            "years": horizon,
            "contributed_minor": monthly * 12 * horizon,
            "projection_minor": {"cautious": low, "middle": mid, "strong": high},
            "fits_profile": risk_score is None or template.risk_level <= risk_score,
            "best_fit": template.key == best.key,
        })
    return {
        "plans": plans,
        "monthly_minor": monthly,
        "years": horizon,
        "note": (
            "Projections assume the yearly returns shown and monthly investing; they are "
            "illustrations, not promises. Real returns vary and can be negative."
        ),
        "disclaimer": market.DISCLAIMER,
    }


# ------------------------------------------------------------ suggestions
def trending(now: datetime, risk_score: int | None) -> dict:
    scored = []
    for instrument in market.CATALOG:
        snap = market.snapshot(instrument.symbol, now)
        momentum = 0.6 * snap["change_3m_pct"] + 0.4 * snap["change_1m_pct"]
        scored.append((momentum, snap))
    scored.sort(key=lambda item: item[0], reverse=True)

    def fit(snap: dict) -> dict:
        above = risk_score is not None and snap["risk_level"] > risk_score
        return {
            **snap,
            "fits_profile": not above,
            "fit_note": (
                f"Riskier than your profile (risk {snap['risk_level']} of 5, yours is {risk_score})."
                if above else f"Within your risk profile (risk {snap['risk_level']} of 5)."
            ) if risk_score is not None else f"Risk {snap['risk_level']} of 5.",
        }

    rising = [
        {**fit(snap), "why": f"Up {snap['change_1m_pct']:.1f}% in a month and {snap['change_3m_pct']:.1f}% over three months."}
        for momentum, snap in scored
        if snap["change_1m_pct"] > 0 and snap["change_3m_pct"] > 0
    ][:4]
    income = sorted(
        (fit(market.snapshot(i.symbol, now)) for i in market.CATALOG
         if risk_score is None or i.risk_level <= risk_score),
        key=lambda snap: snap["dividend_yield_pct"], reverse=True,
    )[:2]
    for snap in income:
        snap["why"] = f"Pays about {snap['dividend_yield_pct']:.1f}% a year in dividends."
    return {"trending": rising, "income": income, "disclaimer": market.DISCLAIMER}


# ------------------------------------------------------------ understanding requests
_PAYS_OUT = re.compile(r"\b(?:send|pay|transfer|give|paynow|bank\s+in)\b", re.IGNORECASE)
_BUY = re.compile(r"\b(?:buy|purchase|invest|put)\b", re.IGNORECASE)
_SELL = re.compile(r"\b(?:sell|offload|cash\s+out)\b", re.IGNORECASE)
_MONTHLY = re.compile(r"\b(?:a|per|each|every)\s+month\b|\bmonthly\b", re.IGNORECASE)
_PORTFOLIO = re.compile(r"\b(?:portfolio|my\s+(?:investments|holdings|stocks|shares|etfs?)|how\s+are\s+my\s+investments)\b", re.IGNORECASE)
_PLANS = re.compile(r"\b(?:long[- ]term|retire(?:ment)?|grow\s+my\s+(?:money|wealth|savings)|investment\s+plans?|growth\s+plans?|savings\s+plans?|plans?\s+for\s+the\s+future)\b", re.IGNORECASE)
_TRENDING = re.compile(r"\b(?:trending|hot|top\s+(?:stocks|picks|investments)|what\s+should\s+i\s+(?:buy|invest)|recommend|suggest|best\s+(?:stocks|investments|etfs?)|good\s+investments?)\b", re.IGNORECASE)
_QUOTE = re.compile(r"\b(?:price|quote|how\s+is|how's|doing|tell\s+me\s+about|worth)\b", re.IGNORECASE)
_COUNT = re.compile(r"(?P<n>" + _BARE_NUMBER + r")\s+(?P<unit>shares?|units?|lots?)\b", re.IGNORECASE)
_VERB_COUNT = re.compile(r"\b(?:buy|sell|purchase)\s+(?P<n>\d[\d,]*|" + _BARE_NUMBER + r")\s+(?!dollars?|bucks?|sgd)", re.IGNORECASE)
_ALL = re.compile(r"\b(?:all|everything|entire|whole)\b", re.IGNORECASE)
_HALF = re.compile(r"\bhalf\b", re.IGNORECASE)
_YEARS = re.compile(r"\b(?:for|over|in)\s+(?P<n>\d{1,2})\s+years?\b", re.IGNORECASE)


def _mentions(text: str, phrase: str, *, case: bool = False) -> re.Match | None:
    return re.search(rf"(?<![\w$]){re.escape(phrase)}(?!\w)", text, 0 if case else re.IGNORECASE)


def find_instruments(text: str) -> list[tuple[market.Instrument, str]]:
    found = []
    for instrument in market.CATALOG:
        phrases = [instrument.name, *instrument.aliases]
        match = next((m for p in sorted(phrases, key=len, reverse=True) if (m := _mentions(text, p))), None)
        match = match or _mentions(text, instrument.symbol, case=True) or _mentions(text, instrument.symbol.lower(), case=True)
        if match:
            found.append((instrument, match.group(0)))
    return found


def find_plan_template(text: str) -> PlanTemplate | None:
    for template in PLAN_TEMPLATES:
        if any(_mentions(text, keyword) for keyword in template.keywords):
            return template
    return None


@dataclass(frozen=True)
class InvestIntent:
    kind: str                         # PORTFOLIO, TRENDING, PLANS, QUOTE, BUY, SELL, START_PLAN
    instrument: market.Instrument | None = None
    instrument_evidence: str | None = None
    template: PlanTemplate | None = None
    amount_minor: int | None = None
    amount_evidence: str | None = None
    quantity_e4: int | None = None
    quantity_evidence: str | None = None
    fraction: str | None = None       # ALL or HALF for sells
    years: int | None = None


def _amount(text: str) -> tuple[int | None, str | None]:
    try:
        mentions = derive_amount_mentions_from_text(text)
    except GroundingError:
        raise InvestRejected("AMBIGUOUS_AMOUNT") from None
    marked = [m for m in mentions if re.search(r"\$|sgd|dollar|buck", m.evidence, re.IGNORECASE)]
    if len(marked) > 1:
        raise InvestRejected("AMBIGUOUS_AMOUNT")
    return (marked[0].amount_minor, marked[0].evidence) if marked else (None, None)


def _count(text: str) -> tuple[int | None, str | None]:
    match = _COUNT.search(text) or _VERB_COUNT.search(text)
    if not match:
        return None, None
    raw = match.group("n").replace(",", "")
    try:
        whole = int(raw) if raw.isdigit() else _bare_amount_minor(raw) // 100
    except GroundingError:
        return None, None
    lots = "unit" in match.groupdict() and (match.group("unit") or "").lower().startswith("lot")
    return whole * (100 if lots else 1) * UNIT, match.group(0).strip()


def understand(text: str) -> InvestIntent | None:
    """Recognise an investing request; None means it is not one."""

    if _PAYS_OUT.search(text):
        return None
    instruments = find_instruments(text)
    template = find_plan_template(text)
    if len(instruments) > 1 and not _PORTFOLIO.search(text):
        raise InvestRejected("ONE_INSTRUMENT_PER_ORDER")
    instrument, evidence = instruments[0] if instruments else (None, None)
    years_match = _YEARS.search(text)
    years = int(years_match.group("n")) if years_match else None

    if _SELL.search(text) and instrument:
        fraction = "ALL" if _ALL.search(text) else "HALF" if _HALF.search(text) else None
        quantity, quantity_evidence = (None, None) if fraction else _count(text)
        return InvestIntent("SELL", instrument, evidence, quantity_e4=quantity,
                            quantity_evidence=quantity_evidence, fraction=fraction)
    if _MONTHLY.search(text) and (_BUY.search(text) or instrument or template):
        amount, amount_evidence = _amount(text)
        return InvestIntent("START_PLAN", instrument, evidence, template, amount, amount_evidence, years=years)
    if _BUY.search(text) and instrument:
        amount, amount_evidence = _amount(text)
        quantity, quantity_evidence = (None, None) if amount else _count(text)
        return InvestIntent("BUY", instrument, evidence, amount_minor=amount, amount_evidence=amount_evidence,
                            quantity_e4=quantity, quantity_evidence=quantity_evidence)
    if _PORTFOLIO.search(text):
        return InvestIntent("PORTFOLIO")
    if _PLANS.search(text) or (template and not instrument):
        amount, amount_evidence = _amount(text)
        return InvestIntent("PLANS", template=template, amount_minor=amount, amount_evidence=amount_evidence, years=years)
    if _TRENDING.search(text) or (_BUY.search(text) and re.search(r"\b(?:stocks?|shares?|etfs?|funds?)\b", text, re.IGNORECASE)):
        return InvestIntent("TRENDING")
    if instrument and (_QUOTE.search(text) or len(text.split()) <= 4):
        return InvestIntent("QUOTE", instrument, evidence)
    return None


# ------------------------------------------------------------ orders
def _holding(connection: sqlite3.Connection, user_id: str, symbol: str) -> sqlite3.Row | None:
    return connection.execute(
        "SELECT * FROM holdings WHERE user_id = ? AND symbol = ?", (user_id, symbol)
    ).fetchone()


def _traded_today(connection: sqlite3.Connection, user_id: str, now: datetime) -> int:
    start = now.astimezone(market.SGT).replace(hour=0, minute=0, second=0, microsecond=0)
    row = connection.execute(
        "SELECT COALESCE(SUM(value_minor), 0) FROM trades WHERE user_id = ? AND plan_id IS NULL AND executed_at >= ?",
        (user_id, _utc(start)),
    ).fetchone()
    return row[0]


def _fee(value_minor: int) -> int:
    return max(MIN_FEE_MINOR, math.ceil(value_minor * FEE_BP / 10_000))


def draft_order(
    connection: sqlite3.Connection, *, user_id: str, request_id: str, text: str, intent: InvestIntent, now: datetime
) -> dict:
    investor = profile(connection, user_id)
    if investor is None:
        raise InvestRejected("INVESTOR_PROFILE_REQUIRED")
    savings = connection.execute("SELECT balance_minor, label FROM accounts WHERE account_id = ?", (SOURCE_ACCOUNT_ID,)).fetchone()
    evidence: dict[str, Any] = {"text": text}
    plan: dict | None = None

    if intent.kind == "START_PLAN":
        if intent.amount_minor is None:
            raise InvestRejected("MISSING_MONTHLY_AMOUNT")
        if not PLAN_MIN_MINOR <= intent.amount_minor <= PLAN_MAX_MINOR:
            raise InvestRejected("PLAN_AMOUNT_OUT_OF_RANGE")
        if intent.instrument:
            name = f"Monthly {intent.instrument.name}"
            allocations = [(intent.instrument.symbol, 100)]
            evidence["instrument"] = intent.instrument_evidence
        elif intent.template:
            name, allocations = intent.template.name, list(intent.template.allocations)
            evidence["plan"] = intent.template.name
        else:
            raise InvestRejected("PLAN_NOT_CHOSEN")
        evidence["amount"] = intent.amount_evidence
        risk = max(market.BY_SYMBOL[symbol].risk_level for symbol, _ in allocations)
        day = min(now.astimezone(market.SGT).day, 28)
        plan = {"name": name, "allocations": [{"symbol": s, "percent": p} for s, p in allocations],
                "monthly_minor": intent.amount_minor, "day_of_month": day}
        kind, symbol, quantity, quote, limit, value, fee = "PLAN", None, None, None, None, intent.amount_minor, 0
        total = value
    else:
        instrument = intent.instrument
        assert instrument is not None
        symbol = instrument.symbol
        risk = instrument.risk_level
        quote = market.price_minor(symbol, now)
        evidence["instrument"] = intent.instrument_evidence
        if intent.kind == "BUY":
            kind = "BUY"
            if intent.amount_minor is not None:
                whole = intent.amount_minor // quote
                if whole < 1:
                    raise InvestRejected("AMOUNT_BELOW_ONE_UNIT")
                quantity = whole * UNIT
                evidence["amount"] = intent.amount_evidence
            elif intent.quantity_e4:
                quantity = intent.quantity_e4
                evidence["quantity"] = intent.quantity_evidence
            else:
                raise InvestRejected("MISSING_QUANTITY")
            limit = math.ceil(quote * (10_000 + PRICE_PROTECTION_BP) / 10_000)
        else:
            kind = "SELL"
            held = _holding(connection, user_id, symbol)
            owned = held["quantity_e4"] if held else 0
            if owned <= 0:
                raise InvestRejected("NOT_HELD")
            if intent.fraction == "ALL":
                quantity = owned
            elif intent.fraction == "HALF":
                quantity = max(UNIT // 10_000, owned // 2)
            elif intent.quantity_e4:
                quantity = intent.quantity_e4
            else:
                raise InvestRejected("MISSING_QUANTITY")
            if quantity > owned:
                raise InvestRejected("SELL_MORE_THAN_HELD")
            evidence["quantity"] = intent.quantity_evidence or intent.fraction
            limit = math.floor(quote * (10_000 - PRICE_PROTECTION_BP) / 10_000)
        value = round(quantity * quote / UNIT)
        fee = _fee(value)
        total = round(quantity * limit / UNIT) + fee if kind == "BUY" else value - fee
        if total <= 0:
            raise InvestRejected("ORDER_TOO_SMALL")
        if value > MAX_ORDER_MINOR:
            raise InvestRejected("ORDER_LIMIT_EXCEEDED")
        if _traded_today(connection, user_id, now) + value > DAILY_TRADING_LIMIT_MINOR:
            raise InvestRejected("DAILY_TRADING_LIMIT_EXCEEDED")

    if kind in ("BUY", "PLAN") and total > savings["balance_minor"]:
        raise InvestRejected("INSUFFICIENT_FUNDS")
    order_id = f"order_{secrets.token_hex(16)}"
    expires_at = _utc(now + ORDER_TTL)
    payload = {
        "contract": "dimon-order-v1",
        "order_id": order_id,
        "user_id": user_id,
        "kind": kind,
        "symbol": symbol,
        "quantity_e4": quantity,
        "quote_price_minor": quote,
        "limit_price_minor": limit,
        "value_minor": value,
        "fee_minor": fee,
        "total_minor": total,
        "plan": plan,
        "source_account_id": SOURCE_ACCOUNT_ID,
        "risk_ack_required": risk > investor["risk_score"],
        "original_text": text,
        "expires_at": expires_at,
        "nonce": secrets.token_hex(16),
    }
    canonical = canonical_json(payload)
    digest = digest_canonical(canonical)
    connection.execute(
        """
        INSERT INTO investment_orders (
          order_id, request_id, user_id, kind, symbol, quantity_e4, quote_price_minor,
          limit_price_minor, value_minor, fee_minor, total_minor, plan_json, risk_ack_required,
          source_account_id, original_text, evidence_json, canonical_json, order_digest,
          status, expires_at, created_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'AWAITING_CONFIRMATION', ?, ?)
        """,
        (order_id, request_id, user_id, kind, symbol, quantity, quote, limit, value, fee, total,
         json.dumps(plan) if plan else None, int(payload["risk_ack_required"]), SOURCE_ACCOUNT_ID,
         text, json.dumps(evidence, sort_keys=True), canonical, digest, expires_at, _utc(now)),
    )
    audit_log.append(connection, "ORDER_DRAFTED", {"order_id": order_id, "order_digest": digest, "kind": kind,
                     "symbol": symbol, "quantity_e4": quantity, "total_minor": total}, now=now,
                     request_id=request_id, receipt_id=order_id)
    return public_order(connection, order_id, now)


def order_title(row: Any) -> str:
    if row["kind"] == "PLAN":
        plan = json.loads(row["plan_json"])
        return f"Start {plan['name']}: {money(plan['monthly_minor'])} a month"
    name = market.BY_SYMBOL[row["symbol"]].name
    verb = "Buy" if row["kind"] == "BUY" else "Sell"
    return f"{verb} {units(row['quantity_e4'])} × {name} ({row['symbol']})"


def public_order(connection: sqlite3.Connection, order_id: str, now: datetime) -> dict:
    row = connection.execute("SELECT * FROM investment_orders WHERE order_id = ?", (order_id,)).fetchone()
    investor = profile(connection, row["user_id"])
    plan = json.loads(row["plan_json"]) if row["plan_json"] else None
    if plan:
        for allocation in plan["allocations"]:
            instrument = market.BY_SYMBOL[allocation["symbol"]]
            allocation.update(name=instrument.name, risk_level=instrument.risk_level,
                              amount_minor=plan["monthly_minor"] * allocation["percent"] // 100)
    instrument = market.BY_SYMBOL.get(row["symbol"] or "")
    return {
        "order_id": row["order_id"],
        "order_digest": row["order_digest"],
        "receipt_id": row["order_id"],
        "receipt_digest": row["order_digest"],
        "kind": row["kind"],
        "title": order_title(row),
        "symbol": row["symbol"],
        "instrument": market.snapshot(row["symbol"], now) if instrument else None,
        "quantity_e4": row["quantity_e4"],
        "quantity": units(row["quantity_e4"]) if row["quantity_e4"] else None,
        "quote_price_minor": row["quote_price_minor"],
        "limit_price_minor": row["limit_price_minor"],
        "value_minor": row["value_minor"],
        "fee_minor": row["fee_minor"],
        "total_minor": row["total_minor"],
        "plan": plan,
        "risk_ack_required": bool(row["risk_ack_required"]),
        "profile": investor,
        "source_label": "savings",
        "status": row["status"],
        "expires_at": row["expires_at"],
        "requires_read_back": row["total_minor"] >= READ_BACK_MINOR,
        "requires_out_of_band": row["total_minor"] > TOKEN_ABOVE_MINOR,
    }


def order_review(connection: sqlite3.Connection, row: Any, now: datetime) -> dict:
    """What the confirmation overlay shows, from the stored order only."""

    order = public_order(connection, row["order_id"], now)
    if order["plan"]:
        items = [
            {"recipient_display_name": f"{a['name']} ({a['symbol']}) · {a['percent']}%",
             "masked_destination": "monthly", "amount_minor": a["amount_minor"]}
            for a in order["plan"]["allocations"]
        ]
    else:
        each = "up to" if row["kind"] == "BUY" else "at least"
        items = [{
            "recipient_display_name": order["title"],
            "masked_destination": f"{each} {money(row['limit_price_minor'])} each · fee {money(row['fee_minor'])}",
            "amount_minor": row["total_minor"],
        }]
    risky = order["risk_ack_required"]
    investor = order["profile"] or {}
    return {
        "kind": "ORDER",
        "order_kind": row["kind"],
        "receipt_id": row["order_id"],
        "receipt_digest": row["order_digest"],
        "source_label": "savings" if row["kind"] != "SELL" else "savings (proceeds paid in)",
        "currency": "SGD",
        "total_minor": row["total_minor"],
        "items": items,
        "receipt_expires_at": row["expires_at"],
        "validation": {"verdict": "PASS", "fields": [], "note": "Authorised in your Singpass app. Built by fixed rules from your own words; the AI took no part in this order."},
        "requires_singpass": True,
        "requires_out_of_band": order["requires_out_of_band"],
        "requires_read_back": order["requires_read_back"],
        "requires_unusual_confirmation": risky,
        "confirmation_text": (
            f"I understand this is riskier than my profile ({investor.get('risk_label', '')}, "
            f"risk {investor.get('risk_score')} of 5) and I could lose money."
        ) if risky else None,
        "read_back": {"text": order_read_back(order), "audio_artifact_id": None},
    }


def order_read_back(order: dict) -> str:
    if order["plan"]:
        parts = ", ".join(f"{a['percent']} percent {a['name']}" for a in order["plan"]["allocations"])
        return (f"Start the {order['plan']['name']} plan: {money(order['plan']['monthly_minor'])} every month from savings, "
                f"split {parts}. The first instalment is invested now. "
                "If this is right, confirm with your face.")
    if order["kind"] == "BUY":
        text = (f"Buy {order['quantity']} units of {order['instrument']['name']} at up to {money(order['limit_price_minor'])} each. "
                f"At most {money(order['total_minor'])} leaves your savings, including a {money(order['fee_minor'])} fee.")
    else:
        text = (f"Sell {order['quantity']} units of {order['instrument']['name']} at no less than {money(order['limit_price_minor'])} each. "
                f"About {money(order['total_minor'])} is paid into your savings after the fee.")
    if order["risk_ack_required"]:
        text += " This is riskier than your investor profile."
    return text + " If this is right, confirm with your face."


# ------------------------------------------------------------ execution
def _settle_trade(connection: sqlite3.Connection, *, user_id: str, symbol: str, side: str, quantity_e4: int,
                  price_minor: int, fee_minor: int, now: datetime, order_id: str | None = None,
                  plan_id: str | None = None) -> dict:
    value = round(quantity_e4 * price_minor / UNIT)
    cash = value + fee_minor if side == "BUY" else value - fee_minor
    delta = -cash if side == "BUY" else cash
    updated = connection.execute(
        "UPDATE accounts SET balance_minor = balance_minor + ? WHERE account_id = ? AND balance_minor + ? >= 0",
        (delta, SOURCE_ACCOUNT_ID, delta),
    )
    if updated.rowcount != 1:
        raise InvestRejected("INSUFFICIENT_FUNDS", persist=True)
    held = _holding(connection, user_id, symbol)
    quantity, cost = (held["quantity_e4"], held["cost_minor"]) if held else (0, 0)
    if side == "BUY":
        quantity, cost = quantity + quantity_e4, cost + cash
    else:
        if quantity_e4 > quantity:
            raise InvestRejected("SELL_MORE_THAN_HELD", persist=True)
        cost = cost - round(cost * quantity_e4 / quantity)
        quantity -= quantity_e4
    connection.execute(
        """
        INSERT INTO holdings (user_id, symbol, quantity_e4, cost_minor) VALUES (?, ?, ?, ?)
        ON CONFLICT(user_id, symbol) DO UPDATE SET quantity_e4 = excluded.quantity_e4, cost_minor = excluded.cost_minor
        """,
        (user_id, symbol, quantity, cost),
    )
    trade = {"trade_id": f"trade_{secrets.token_hex(12)}", "order_id": order_id, "plan_id": plan_id,
             "user_id": user_id, "symbol": symbol, "side": side, "quantity_e4": quantity_e4,
             "price_minor": price_minor, "value_minor": value, "fee_minor": fee_minor,
             "cash_minor": cash, "executed_at": _utc(now)}
    connection.execute(f"INSERT INTO trades ({', '.join(trade)}) VALUES ({', '.join('?' for _ in trade)})",
                       tuple(trade.values()))
    # Double entry: savings on one side, the broker's clearing account on the other.
    connection.executemany(
        "INSERT INTO investment_cash_entries (entry_id, trade_id, account_ref, delta_minor) VALUES (?, ?, ?, ?)",
        [(f"ientry_{secrets.token_hex(12)}", trade["trade_id"], SOURCE_ACCOUNT_ID, delta),
         (f"ientry_{secrets.token_hex(12)}", trade["trade_id"], BROKER_CLEARING, -delta)],
    )
    return {**trade, "name": market.BY_SYMBOL[symbol].name, "quantity": units(quantity_e4)}


def _invest_instalment(connection: sqlite3.Connection, plan: sqlite3.Row | dict, now: datetime) -> list[dict]:
    allocations = json.loads(plan["allocations_json"])
    trades = []
    for allocation in allocations:
        amount = plan["monthly_minor"] * allocation["percent"] // 100
        price = market.price_minor(allocation["symbol"], now)
        quantity = amount * UNIT // price
        if quantity > 0:
            trades.append(_settle_trade(connection, user_id=plan["user_id"], symbol=allocation["symbol"], side="BUY",
                                        quantity_e4=quantity, price_minor=price, fee_minor=0, now=now,
                                        plan_id=plan["plan_id"]))
    return trades


def _add_month(moment: datetime, day: int) -> datetime:
    local = moment.astimezone(market.SGT)
    year, month = (local.year + 1, 1) if local.month == 12 else (local.year, local.month + 1)
    day = min(day, calendar.monthrange(year, month)[1])
    return local.replace(year=year, month=month, day=day, hour=9, minute=0, second=0, microsecond=0)


def execute_order(connection: sqlite3.Connection, row: Any, now: datetime) -> dict:
    """Fill a signed order at the live price, inside the caller's transaction."""

    if row["kind"] == "PLAN":
        plan_spec = json.loads(row["plan_json"])
        plan = {
            "plan_id": f"plan_{secrets.token_hex(12)}", "order_id": row["order_id"], "user_id": row["user_id"],
            "name": plan_spec["name"], "allocations_json": json.dumps(plan_spec["allocations"]),
            "monthly_minor": plan_spec["monthly_minor"], "day_of_month": plan_spec["day_of_month"],
            "status": "ACTIVE", "next_run_at": _utc(_add_month(now, plan_spec["day_of_month"])),
            "created_at": _utc(now),
        }
        connection.execute(f"INSERT INTO investment_plans ({', '.join(plan)}) VALUES ({', '.join('?' for _ in plan)})",
                           tuple(plan.values()))
        trades = _invest_instalment(connection, plan, now)
        connection.execute(
            "INSERT INTO plan_runs (run_id, plan_id, due_at, status, amount_minor, ran_at) VALUES (?, ?, ?, 'INVESTED', ?, ?)",
            (f"run_{secrets.token_hex(12)}", plan["plan_id"], _utc(now), sum(t["cash_minor"] for t in trades), _utc(now)),
        )
        audit_log.append(connection, "INVESTMENT_PLAN_STARTED", {"plan_id": plan["plan_id"], "order_id": row["order_id"],
                         "monthly_minor": plan["monthly_minor"], "name": plan["name"]}, now=now, receipt_id=row["order_id"])
        return {"plan": {k: plan[k] for k in ("plan_id", "name", "monthly_minor", "next_run_at")}, "trades": trades}

    price = market.price_minor(row["symbol"], now)
    if (row["kind"] == "BUY" and price > row["limit_price_minor"]) or (
        row["kind"] == "SELL" and price < row["limit_price_minor"]
    ):
        raise InvestRejected("PRICE_MOVED_BEYOND_LIMIT", persist=True)
    trade = _settle_trade(connection, user_id=row["user_id"], symbol=row["symbol"], side=row["kind"],
                          quantity_e4=row["quantity_e4"], price_minor=price, fee_minor=row["fee_minor"], now=now,
                          order_id=row["order_id"])
    audit_log.append(connection, "TRADE_EXECUTED", {k: trade[k] for k in (
        "trade_id", "symbol", "side", "quantity_e4", "price_minor", "value_minor", "fee_minor", "cash_minor")},
        now=now, receipt_id=row["order_id"])
    return {"trades": [trade]}


def run_due_plans(connection: sqlite3.Connection, user_id: str, now: datetime) -> list[dict]:
    """Invest any monthly instalments that have fallen due (standing instructions
    the account holder confirmed with their face when starting the plan)."""

    runs = []
    for plan in connection.execute(
        "SELECT * FROM investment_plans WHERE user_id = ? AND status = 'ACTIVE' AND next_run_at <= ?",
        (user_id, _utc(now)),
    ).fetchall():
        due = datetime.fromisoformat(plan["next_run_at"])
        for _ in range(12):
            if due > now:
                break
            savings = connection.execute("SELECT balance_minor FROM accounts WHERE account_id = ?", (SOURCE_ACCOUNT_ID,)).fetchone()
            if savings["balance_minor"] >= plan["monthly_minor"]:
                trades = _invest_instalment(connection, plan, due)
                status, amount = "INVESTED", sum(t["cash_minor"] for t in trades)
            else:
                status, amount = "SKIPPED_INSUFFICIENT_FUNDS", 0
            connection.execute(
                "INSERT OR IGNORE INTO plan_runs (run_id, plan_id, due_at, status, amount_minor, ran_at) VALUES (?, ?, ?, ?, ?, ?)",
                (f"run_{secrets.token_hex(12)}", plan["plan_id"], _utc(due), status, amount, _utc(now)),
            )
            audit_log.append(connection, "PLAN_INSTALMENT", {"plan_id": plan["plan_id"], "due_at": _utc(due),
                             "status": status, "amount_minor": amount}, now=now)
            runs.append({"plan_id": plan["plan_id"], "due_at": _utc(due), "status": status, "amount_minor": amount})
            due = _add_month(due, plan["day_of_month"])
        connection.execute("UPDATE investment_plans SET next_run_at = ? WHERE plan_id = ?", (_utc(due), plan["plan_id"]))
    return runs


def cancel_plan(connection: sqlite3.Connection, user_id: str, plan_id: str, now: datetime) -> None:
    """Stopping a plan only reduces risk, so it needs no signature."""

    updated = connection.execute(
        "UPDATE investment_plans SET status = 'CANCELLED', cancelled_at = ? WHERE plan_id = ? AND user_id = ? AND status = 'ACTIVE'",
        (_utc(now), plan_id, user_id),
    )
    if updated.rowcount != 1:
        raise InvestRejected("PLAN_NOT_FOUND")
    audit_log.append(connection, "INVESTMENT_PLAN_CANCELLED", {"plan_id": plan_id}, now=now)


