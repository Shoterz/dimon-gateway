class InvestRejected(ValueError):
    def __init__(self, reason_code: str, *, persist: bool = False):
        super().__init__(reason_code)
        self.reason_code = reason_code
        self.persist = persist


def _utc(value: datetime) -> str:
    return value.astimezone(timezone.utc).isoformat()


def money(minor: int) -> str:
    return f"S${minor / 100:,.2f}"


def units(quantity_e4: int) -> str:
    if quantity_e4 % UNIT == 0:
        return f"{quantity_e4 // UNIT:,}"
    return f"{quantity_e4 / UNIT:,.4f}".rstrip("0").rstrip(".")


# ------------------------------------------------------------ risk profile
QUESTIONS = (
    {"id": "horizon", "text": "When will you need this money?",
     "options": ["Within 3 years", "In 3 to 7 years", "In 7 to 15 years", "More than 15 years away"]},
    {"id": "drop", "text": "If your investments fell 20% in a few months, you would…",
     "options": ["Sell everything", "Sell some", "Hold and wait", "Buy more"]},
    {"id": "experience", "text": "Your investing experience",
     "options": ["None", "Unit trusts, ETFs or savings plans", "I buy shares regularly", "Experienced, including complex products"]},
    {"id": "goal", "text": "Your main goal",
     "options": ["Keep my money safe", "Regular income", "Balanced growth", "Maximum long-term growth"]},
)
HORIZON_YEARS = {1: 2, 2: 5, 3: 10, 4: 20}


def score_profile(answers: dict[str, int]) -> tuple[int, int]:
    if set(answers) != {q["id"] for q in QUESTIONS} or not all(
        isinstance(v, int) and 1 <= v <= 4 for v in answers.values()
    ):
        raise InvestRejected("INVESTOR_PROFILE_INVALID")
    total = sum(answers.values())
    risk = 1 if total <= 6 else 2 if total <= 8 else 3 if total <= 11 else 4 if total <= 13 else 5
    # Someone who would sell everything after a fall is never rated above balanced.
    if answers["drop"] == 1:
        risk = min(risk, 3)
    return risk, HORIZON_YEARS[answers["horizon"]]


RISK_LABELS = {1: "Very cautious", 2: "Cautious", 3: "Balanced", 4: "Growth", 5: "Adventurous"}


def save_profile(connection: sqlite3.Connection, user_id: str, answers: dict[str, int], acknowledged: bool, now: datetime) -> dict:
    if not acknowledged:
        raise InvestRejected("INVESTMENT_RISK_NOT_ACKNOWLEDGED")
    risk, horizon = score_profile(answers)
    connection.execute(
        """
        INSERT INTO investor_profiles (user_id, risk_score, horizon_years, answers_json, completed_at)
        VALUES (?, ?, ?, ?, ?)
        ON CONFLICT(user_id) DO UPDATE SET risk_score = excluded.risk_score,
          horizon_years = excluded.horizon_years, answers_json = excluded.answers_json,
          completed_at = excluded.completed_at
        """,
        (user_id, risk, horizon, json.dumps(answers, sort_keys=True), _utc(now)),
    )
    audit_log.append(connection, "INVESTOR_PROFILE_SAVED", {"risk_score": risk, "horizon_years": horizon}, now=now)
    return profile(connection, user_id)


def profile(connection: sqlite3.Connection, user_id: str) -> dict | None:
    row = connection.execute("SELECT * FROM investor_profiles WHERE user_id = ?", (user_id,)).fetchone()
    if row is None:
        return None
    return {
        "risk_score": row["risk_score"],
        "risk_label": RISK_LABELS[row["risk_score"]],
        "horizon_years": row["horizon_years"],
        "completed_at": row["completed_at"],
    }


